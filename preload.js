'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('native', {
  browser: false,
  openFiles: (opts) => ipcRenderer.invoke('open-files', opts),
  readFile: (p) => ipcRenderer.invoke('read-file', p),
  saveFile: (opts) => ipcRenderer.invoke('save-file', opts),
  writeFile: (p, data) => ipcRenderer.invoke('write-file', p, data),
  pickFolder: () => ipcRenderer.invoke('pick-folder'),
  watchPath: (p) => ipcRenderer.invoke('watch-path', p),
  unwatchPath: (p) => ipcRenderer.invoke('unwatch-path', p),
  onPathChanged: (cb) => ipcRenderer.on('path-changed', (_e, p, t) => cb(p, t)),
  stat: (p) => ipcRenderer.invoke('file-stat', p),
  deleteFile: (p) => ipcRenderer.invoke('delete-file', p),
  showInFolder: (p) => ipcRenderer.invoke('show-in-folder', p),
  userInfo: () => ipcRenderer.invoke('user-info'),
  cloudFolders: () => ipcRenderer.invoke('cloud-folders'),
  findCameraProfiles: (m, mk) => ipcRenderer.invoke('find-camera-profiles', m, mk),
  listFiles: (d, p) => ipcRenderer.invoke('list-files', d, p),
  openExternal: (u) => ipcRenderer.invoke('open-external', u),
  dngConvert: (p) => ipcRenderer.invoke('dng-convert', p),
  rtHostStart: (port) => ipcRenderer.invoke('rt-host-start', port),
  rtHostStop: () => ipcRenderer.invoke('rt-host-stop'),
  readClipboardImage: () => ipcRenderer.invoke('clipboard-read-image'),
  writeClipboardImage: (data) => ipcRenderer.invoke('clipboard-write-image', data),
  pathForFile: (f) => { try { return webUtils.getPathForFile(f); } catch (_) { return null; } },
  aiRequest: (req) => ipcRenderer.invoke('ai-request', req),
  licenseMachine: () => ipcRenderer.invoke('license-machine'),
  licenseLoad: () => ipcRenderer.invoke('license-load'),
  licenseSave: (d) => ipcRenderer.invoke('license-save', d),
  photoApi: (req) => ipcRenderer.invoke('photo-api', req),
  photoServer: () => ipcRenderer.invoke('photo-server'),
  setDirty: (v) => ipcRenderer.send('set-dirty', v),
  toggleFullscreen: () => ipcRenderer.send('toggle-fullscreen'),
  quit: () => ipcRenderer.send('quit'),
  ready: () => ipcRenderer.send('renderer-ready'),
  onOpenPaths: (cb) => ipcRenderer.on('open-paths', (_e, files) => cb(files)),
});
